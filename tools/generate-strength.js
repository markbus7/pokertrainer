/**
 * Generates src/js/data/handStrength.js — each of the 169 starting hands
 * scored by its all-in equity against one random hand.
 *
 * Run: node tools/generate-strength.js
 */
import { writeFileSync } from 'node:fs';
import { ALL_HAND_KEYS, expandHandKey, makeDeck } from '../src/js/core/cards.js';
import { evaluate } from '../src/js/core/evaluator.js';
import { makeRng } from '../src/js/core/rng.js';

const TRIALS = Number(process.argv[2] || 60000);
const rng = makeRng(20260828);
const table = {};

const started = Date.now();
for (const key of ALL_HAND_KEYS) {
  const hero = expandHandKey(key)[0];       // suits are symmetric preflop
  const blocked = new Set(hero);
  const pool = makeDeck().filter((c) => !blocked.has(c));
  let total = 0;

  for (let t = 0; t < TRIALS; t++) {
    // Partial Fisher-Yates for the 7 cards we need: 2 villain + 5 board.
    for (let k = 0; k < 7; k++) {
      const j = k + Math.floor(rng() * (pool.length - k));
      const tmp = pool[k]; pool[k] = pool[j]; pool[j] = tmp;
    }
    const board = [pool[2], pool[3], pool[4], pool[5], pool[6]];
    const h = evaluate([hero[0], hero[1], ...board]);
    const v = evaluate([pool[0], pool[1], ...board]);
    total += h > v ? 1 : h === v ? 0.5 : 0;
  }
  table[key] = Number((total / TRIALS).toFixed(4));
}

const ordered = [...ALL_HAND_KEYS].sort((a, b) => table[b] - table[a]);
const lines = ordered.map((k) => `  ${JSON.stringify(k)}: ${table[k].toFixed(4)},`);
// Pair keys like '22' are integer-like, and JS hoists those to the front of
// any object. The ranking therefore has to be its own array.
const orderLiteral = ordered.map((k) => JSON.stringify(k)).join(', ');

writeFileSync(
  new URL('../src/js/data/handStrength.js', import.meta.url),
  `/**
 * All-in equity of each starting hand against one random hand.
 * Generated by tools/generate-strength.js (${TRIALS.toLocaleString('en-US')} trials per hand).
 * Ordered strongest first, so Object.keys() is a preflop hand ranking.
 */
export const HAND_STRENGTH = Object.freeze({
${lines.join('\n')}
});

/** Every starting hand, strongest first. */
export const STRENGTH_ORDER = Object.freeze([
  ${orderLiteral},
]);

/** 1 = best starting hand, 169 = worst. */
export const STRENGTH_RANK = Object.freeze(
  STRENGTH_ORDER.reduce((acc, key, i) => { acc[key] = i + 1; return acc; }, {})
);
`,
);

console.log(`Wrote 169 hands in ${((Date.now() - started) / 1000).toFixed(1)}s`);
console.log('Best :', ordered.slice(0, 6).map((k) => `${k} ${(table[k] * 100).toFixed(1)}%`).join('  '));
console.log('Worst:', ordered.slice(-6).map((k) => `${k} ${(table[k] * 100).toFixed(1)}%`).join('  '));
