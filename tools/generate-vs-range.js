/**
 * Generates src/js/data/rangeEquity.js — each of the 169 starting hands
 * scored against the opening range of each position, rather than against a
 * random hand.
 *
 * This is the number that actually decides preflop calls. Against a random
 * hand K-Q wins 62%; against the range an early-position player is willing
 * to raise with, it wins 45%. Precomputed because a drill cannot afford to
 * run 20,000 showdowns while the reader waits.
 *
 * Run: node tools/generate-vs-range.js [trials]
 */
import { writeFileSync } from 'node:fs';
import { ALL_HAND_KEYS, expandHandKey, makeDeck } from '../src/js/core/cards.js';
import { evaluate } from '../src/js/core/evaluator.js';
import { makeRng } from '../src/js/core/rng.js';
import { RFI, parseRange, rangePercent } from '../src/js/data/ranges.js';

const TRIALS = Number(process.argv[2] || 12000);
const rng = makeRng(20260909);
const POSITIONS = ['UTG', 'HJ', 'CO', 'BTN'];

const started = Date.now();
const table = {};
const sizes = {};

for (const pos of POSITIONS) {
  const keys = [...parseRange(RFI[pos])];
  const combos = keys.flatMap((k) => expandHandKey(k));
  sizes[pos] = Math.round(rangePercent(parseRange(RFI[pos])) * 100);
  table[pos] = {};

  for (const key of ALL_HAND_KEYS) {
    const hero = expandHandKey(key)[0];       // suits are symmetric preflop
    const blocked = new Set(hero);
    // A hand the hero holds cards from cannot be in the villain's range.
    const live = combos.filter((c) => !c.some((card) => blocked.has(card)));
    if (!live.length) { table[pos][key] = 0.5; continue; }

    let total = 0;
    for (let t = 0; t < TRIALS; t++) {
      const villain = live[Math.floor(rng() * live.length)];
      const dead = new Set([...hero, ...villain]);
      const pool = makeDeck().filter((c) => !dead.has(c));
      for (let k = 0; k < 5; k++) {
        const j = k + Math.floor(rng() * (pool.length - k));
        const tmp = pool[k]; pool[k] = pool[j]; pool[j] = tmp;
      }
      const board = pool.slice(0, 5);
      const h = evaluate([hero[0], hero[1], ...board]);
      const v = evaluate([villain[0], villain[1], ...board]);
      total += h > v ? 1 : h === v ? 0.5 : 0;
    }
    table[pos][key] = Number((total / TRIALS).toFixed(4));
  }
  console.log(`  ${pos} (top ${sizes[pos]}%) done — ${((Date.now() - started) / 1000).toFixed(0)}s`);
}

const block = (pos) => `  ${pos}: Object.freeze({\n${
  ALL_HAND_KEYS.map((k) => `    ${JSON.stringify(k)}: ${table[pos][k].toFixed(4)},`).join('\n')
}\n  }),`;

writeFileSync(
  new URL('../src/js/data/rangeEquity.js', import.meta.url),
  `/**
 * All-in equity of each starting hand against the range a position actually
 * opens with — not against a random hand.
 *
 * Generated by tools/generate-vs-range.js (${TRIALS.toLocaleString('en-US')} trials per hand per position).
 * Do not edit by hand.
 */

/** How wide each opening range is, as a percentage of all hands. */
export const RANGE_WIDTH = Object.freeze(${JSON.stringify(sizes)});

export const VS_RANGE = Object.freeze({
${POSITIONS.map(block).join('\n')}
});

export const RANGE_POSITIONS = Object.freeze(${JSON.stringify(POSITIONS)});
`,
);

console.log(`Wrote ${POSITIONS.length} × 169 numbers in ${((Date.now() - started) / 1000).toFixed(1)}s`);
